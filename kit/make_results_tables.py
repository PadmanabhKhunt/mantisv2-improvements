"""Builds results/RESULTS.md (report-ready tables for all 18 datasets) from every kit-format CSV under results/.

    python kit/make_results_tables.py
"""
import glob
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / 'results'

# Tables 2 and 3 of the MantisV2 paper, in order; value = MantisV2 accuracy reported in the paper
DATASETS = [('Ego4D', 0.5258), ('EMOPain', 0.8798), ('HHAR-ID', 0.9845), ('HHAR-OOD', 0.5822), ('MP8', 0.6857),
            ('MP50', 0.7345), ('UCI-HAR', 0.9013), ('Blink', 0.9956), ('CAP-ID', 0.8152), ('CAP-OOD', 0.7859),
            ('Epilepsy-EEG', 0.9558), ('FingerMovements', 0.5500), ('PCL-ID', 0.5716), ('PCL-OOD', 0.5311),
            ('SEDFx-ID', 0.8000), ('SEDFx-OOD', 0.7636), ('SelfRegulationSCP1', 0.8134), ('SelfRegulationSCP2', 0.5167)]
OWNER = {i: 'Aadil' for i in range(1, 7)} | {i: 'Padmanabh' for i in range(7, 13)} | {i: 'Praneet' for i in range(13, 19)}
NOT_RUN = {'Ego4D': 'not run: the data needs a signed Ego4D licence agreement, so it is not freely downloadable'}
METHODS = ['rf', 'logreg', 'head', 'mixer', 'pool', 'pool_mixer', 'lora']
NAMES = {'rf': 'RF (paper)', 'logreg': 'LogReg', 'head': 'Head', 'mixer': 'Mixer v2 (idea 1)', 'pool': 'Pooling (idea 2)',
         'pool_mixer': 'Idea 2 + mixer', 'lora': 'LoRA + mixer (idea 3)'}

frames = []
# later files win when the same (dataset, method) appears twice: first the old datasets 7-12 summary, then the
# main kit runs, then re-runs (part 5 / idea 2 fill-ins) that replace failed or older numbers
order = lambda f: (0 if 'datasets_7_12' in f else 2 if ('part5' in f or 'idea2' in f) else 1, f)
for f in sorted(glob.glob(str(RES / '**' / '*results.csv'), recursive=True), key=order):
    cols = pd.read_csv(f, nrows=0).columns
    if {'dataset', 'method', 'mean', 'std'} <= set(cols) and 'paper' in cols:
        frames.append(pd.read_csv(f))
df = pd.concat(frames).drop_duplicates(['dataset', 'method'], keep='last')
mean = df.pivot(index='dataset', columns='method', values='mean')
std = df.pivot(index='dataset', columns='method', values='std')

out = ['# Results: MantisV2 reproduction and improvements on the 18 datasets of Tables 2 and 3', '',
       'Accuracy on the test split, mean ± std over 3 seeds (logistic regression is deterministic, so 1 run). '
       'Generated by `kit/make_results_tables.py` from the CSVs in `results/`.', '']

# ---- 1. reproduction
out += ['## 1. Reproduction (frozen MantisV2 + Random Forest, paper protocol)', '',
        '| # | Dataset | Paper | Ours | Difference |', '|---|---|---|---|---|']
diffs = []
for i, (name, paper) in enumerate(DATASETS, 1):
    if name in NOT_RUN or name not in mean.index or 'rf' not in mean.columns or pd.isna(mean.loc[name].get('rf')):
        out.append(f'| {i} | {name} | {paper:.4f} | — | {NOT_RUN.get(name, "not run")} |')
        continue
    m, s = mean.loc[name, 'rf'], std.loc[name, 'rf']
    diffs.append(m - paper)
    out.append(f'| {i} | {name} | {paper:.4f} | {m:.4f} ± {s:.4f} | {m - paper:+.4f} |')
d = np.abs(diffs)
out += ['', f'{len(diffs)} datasets reproduced. Within 0.01 of the paper: {(d <= 0.01).sum()}; '
        f'within 0.02: {(d <= 0.02).sum()}; mean absolute difference {d.mean():.4f}.', '']

# ---- 2. improvements
out += ['## 2. Improvements (same frozen encoder; best per row in bold)', '',
        '| # | Dataset | ' + ' | '.join(NAMES[m] for m in METHODS) + ' |', '|---|---|' + '---|' * len(METHODS)]
rows_done = []
for i, (name, _) in enumerate(DATASETS, 1):
    if name not in mean.index:
        continue
    r = mean.loc[name]
    best = max(r.get(m, -1) for m in METHODS if not pd.isna(r.get(m, np.nan)))
    cells = []
    for m in METHODS:
        v = r.get(m, np.nan)
        cells.append('—' if pd.isna(v) else (f'**{v:.4f}**' if abs(v - best) < 1e-9 else f'{v:.4f}'))
    out.append(f'| {i} | {name} | ' + ' | '.join(cells) + ' |')
    rows_done.append(name)

# ---- 3. summary over datasets
sub = mean.loc[rows_done]
full = sub.dropna(subset=['rf', 'mixer', 'lora'])
out += ['', '## 3. Summary across datasets', '',
        '| Method | Datasets run | Mean accuracy (datasets where all of RF, mixer and LoRA ran) | Wins vs RF | Best of all methods |',
        '|---|---|---|---|---|']
best_m = sub[METHODS].idxmax(axis=1)
for m in METHODS:
    if m not in sub.columns:
        continue
    col = sub[m].dropna()
    avg = full[m].mean() if m in full.columns and full[m].notna().all() else np.nan
    wins = int((col > sub.loc[col.index, 'rf']).sum()) if m != 'rf' else '—'
    out.append(f'| {NAMES[m]} | {len(col)} | {"—" if pd.isna(avg) else f"{avg:.4f}"} | {wins} | {int((best_m == m).sum())} |')
out += ['', f'Mean accuracy is over the {len(full)} datasets where RF, mixer v2 and LoRA all ran, so the numbers are comparable.', '']

# ---- 4. gates and layer weights (for the "why" discussion)
if 'gate' in df.columns:
    out += ['## 4. Mixer gate (how much cross-channel mixing the model chose; 0 = none)', '',
            '| Dataset | Channels | Mixer v2 gate (3 seeds) | Idea 2 + mixer gate |', '|---|---|---|---|']
    for name in rows_done:
        g = df[(df.dataset == name)]
        gm = g[g.method == 'mixer'].gate.tolist()
        gp = g[g.method == 'pool_mixer'].gate.tolist()
        ch = g.channels.dropna().iloc[0] if 'channels' in g and g.channels.notna().any() else ''
        gm = [x for x in gm if isinstance(x, str)][-1:]
        gp = [x for x in gp if isinstance(x, str)][-1:]
        fmt = lambda g: g[0] if g and isinstance(g[0], str) else '—'
        out.append(f'| {name} | {"" if ch == "" else int(ch)} | {fmt(gm)} | {fmt(gp)} |')
    out.append('')

(RES / 'RESULTS.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('\n'.join(out))
